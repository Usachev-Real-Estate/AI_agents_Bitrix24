"""Один человек или разные — по имени контакта (раздел 2.4 ТЗ).

Отдельным модулем, потому что ответ нужен двоим и по разным поводам:
правилу ключа — чтобы решить, склеивать ли номер, числящийся за двумя
контактами; разбору портфеля — чтобы посчитать, сколько таких номеров чем
объясняется. Держать одно сравнение в двух местах значит однажды поправить
одно из них.

Почему вообще имя. Измерение живого портфеля (сентябрь, 237 спорных
номеров) разложило их пополам: 116 — один и тот же человек, заведённый
дважды, 120 — действительно разные люди на одном номере (семья, рабочий
телефон, номер брокера в карточке клиента). Значит ни «склеивать всегда»,
ни «не склеивать никогда» не годится, а признак, который их различает,
лежит в карточке и стоит одно сравнение строк.

Сравнивается имя ЦЕЛИКОМ, а не фамилия: в карточках, заведённых автоматом
по входящему звонку, фамилия пуста, а имя лежит в одном поле строкой.
Первая редакция разбора опёрлась на фамилию и отправила в «не знаем» 231
конфликт из 237.
"""

from __future__ import annotations

from typing import Any, Iterable, Mapping

# Порядок полей здесь не важен — отпечаток их сортирует, — но перечень
# важен: это все поля имени, которые отдаёт crm.contact.list.
NAME_FIELDS = ("LAST_NAME", "NAME", "SECOND_NAME")


def name_parts(contact: Mapping[str, Any] | None) -> tuple[str, ...]:
    """Непустые части имени в сравнимом виде.

    Регистр и края убираются: «ИВАНОВ » и «Иванов» — один человек, и
    разойтись они имеют право только в базе, а не в ответе на вопрос.
    """
    if not contact:
        return ()
    return tuple(
        value for value in (
            str(contact.get(field_name) or "").strip().casefold()
            for field_name in NAME_FIELDS
        ) if value
    )


def fingerprint(contact: Mapping[str, Any] | None) -> str:
    """Отпечаток имени. Пустая строка — имени нет вовсе.

    Части сортируются, потому что поля путают местами: «Иванов» в NAME и
    «Иван» в LAST_NAME — обычное дело для карточки, заведённой руками в
    спешке. Сортировка делает сравнение независимым от того, кто куда
    что положил, и при этом не склеивает разные имена: совпасть должен
    ВЕСЬ набор частей.
    """
    return " ".join(sorted(name_parts(contact)))


def one_person(contacts: Iterable[Mapping[str, Any] | None]) -> bool:
    """Все эти карточки — один и тот же человек?

    Да — только если названы ВСЕ и названы одинаково. Безымянная карточка
    рядом с живой почти наверняка её же автоматический двойник, но «почти»
    здесь и есть ответ: цена ошибочной склейки — чужая история и чужой
    ответственный у клиента, и платит её брокер, а не эта функция.
    """
    marks = [fingerprint(contact) for contact in contacts]
    return bool(marks) and all(marks) and len(set(marks)) == 1
