"""Есть ли у звонка расшифровка (правило 3 раздела 6.2 ТЗ).

Третий источник слоя и единственный, без которого он умеет обойтись.
Журнал постановок на расшифровку живёт в `data/violations.db`, таблица
`transcript_launches` (db.py:369) — то есть в базе аудита, а не в витрине.
Открывается она **только на чтение**, тем же способом, что и витрина: у
неё свои писатели, и подсаживаться к ним третьим слой не имеет права.

**Чего в этой таблице нет.** ТЗ описывает правило 3 статусами
`queued | deferred | absent` `[V27]`. Таких значений в базе не бывает: их
вычисляет досье в памяти и кладёт в свою дневную выгрузку `queue_<дата>.json`,
а в `transcript_launches.outcome` записывается ровно три вещи — пусто
(«поставлен, ждём»), `ok` («текст появился») и `failed` («две постановки
без результата»). Читать дневные JSON-файлы ради трёх состояний значило бы
завести четвёртый источник, живущий по своему расписанию и исчезающий при
чистке каталога.

Поэтому правило спрашивает у журнала то, на что журнал умеет ответить:
**есть текст или нет**. Расшифровка считается имеющейся, только если
запись говорит `ok`. Пусто, `failed` и отсутствие записи вовсе — всё это
«текста нет», и по какой именно причине его нет, правилу 3 безразлично:
оно отвечает на вопрос «на чём РОПу принимать решение», а не «почему
очередь не справилась».

База недоступна — правило гаснет и попадает в `degraded_rules`. Падать
нельзя: расшифровки это довесок к портфелю, а не портфель.
"""

from __future__ import annotations

import logging
import sqlite3
from pathlib import Path
from typing import Iterable, Iterator, Sequence

logger = logging.getLogger(__name__)

DEFAULT_DB_PATH = Path("data/violations.db")

# Единственное значение, означающее «текст есть». Словарь досье
# (dossier.py:80), а не наш: заводить свою копию значило бы разойтись с ним
# в тот день, когда там добавят состояние.
TRANSCRIBED = "ok"

# Тот же размер пачки, что у витрины: у SQLite есть потолок числа
# параметров в запросе, и портфель на тридцать тысяч дел в него упрётся
# ночью, а не в тесте.
CHUNK = 500

# Имя правила для degraded_rules. Строкой, а не кодом: список уходит в
# журнал прогонов и читается человеком.
DEGRADED_NAME = "расшифровки звонков"


def _chunks(values: Sequence[int]) -> Iterator[tuple[int, ...]]:
    ordered = tuple(values)
    for start in range(0, len(ordered), CHUNK):
        yield ordered[start:start + CHUNK]


def transcribed_calls(
    activity_ids: Iterable[int],
    *,
    db_path: str | Path | None = None,
) -> set[int] | None:
    """Звонки, у которых расшифровка ЕСТЬ. ``None`` — журнал недоступен.

    Возвращается именно множество расшифрованных, а не словарь исходов:
    правилу 3 нужен один бит, и отдавать ему больше значило бы предложить
    решать за журнал, что означает `failed`.

    ``None`` и пустое множество — разные ответы, и путать их нельзя.
    Пустое значит «журнал прочитан, расшифровок нет ни одной»: правило
    работает и объявляет «нет данных» честно. ``None`` значит «журнала не
    видно», и тогда правило обязано молчать, а не объявлять весь портфель
    безданным.
    """
    wanted = sorted({int(value) for value in activity_ids})
    if not wanted:
        return set()

    path = Path(db_path or DEFAULT_DB_PATH)
    try:
        # Тот же readonly-URI, что у витрины: соединение физически не умеет
        # писать, и случайный INSERT падает здесь, а не портит чужую базу.
        with sqlite3.connect(f"file:{path}?mode=ro", uri=True) as conn:
            out: set[int] = set()
            for chunk in _chunks(wanted):
                marks = ", ".join("?" * len(chunk))
                rows = conn.execute(
                    "SELECT activity_id FROM transcript_launches"
                    f" WHERE outcome = ? AND activity_id IN ({marks})",
                    (TRANSCRIBED, *chunk),
                ).fetchall()
                out.update(int(row[0]) for row in rows)
    except sqlite3.Error as error:
        # Файла нет, таблицы нет, база занята — все три случая одинаковы
        # для вызывающего: правило 3 в этом прогоне не работает.
        logger.warning("Журнал расшифровок недоступен (%s): %s", path, error)
        return None
    return out
