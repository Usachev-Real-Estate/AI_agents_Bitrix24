"""Согласование слов в сообщениях.

Сообщение, которое не согласует слова, выглядит машинным, а машинному
отчёту верят меньше, чем он заслуживает. «31 карточек лежат без работы» —
именно такая строка: числа в ней верные, а доверия она стоит.

Живёт отдельным модулем, потому что нужна и сводке, и советам. Две копии
правила о числительных разошлись бы на первом же исключении — а исключение
в русском счёте одно и хитрое: одиннадцать-четырнадцать ведут себя не как
один-четыре.
"""

from __future__ import annotations


def form(count: int, one: str, few: str, many: str) -> str:
    """Форма существительного под число. Публичная: нужна и вне этого модуля."""
    return _form(count, one, few, many)


def _form(count: int, one: str, few: str, many: str) -> str:
    tail = abs(count) % 100
    if 11 <= tail <= 14:
        return many
    tail %= 10
    if tail == 1:
        return one
    if 2 <= tail <= 4:
        return few
    return many


def cards(count: int) -> str:
    return _form(count, "карточка", "карточки", "карточек")


def deals(count: int) -> str:
    return _form(count, "сделка", "сделки", "сделок")


def verb(count: int, one: str, many: str) -> str:
    """Глагол под число: «лежит 1» против «лежат 3»."""
    return one if _form(count, "1", "2", "5") == "1" else many


def name(text: str, limit: int) -> str:
    """Название карточки для строки отчёта: обрезанное и в кавычках.

    Кавычки нужны затем, что дальше в строке стоит глагол: «Ленинградское
    ш. 12 ушла» читается как ошибка согласования, а «Ленинградское ш. 12»
    ушла — как имя, к которому глагол относится целиком. Род произвольного
    названия коду неизвестен, и кавычки — единственный способ не спорить с
    ним в каждой строке.

    Название со своими кавычками в чужие не заворачивается: матрёшка из
    «ЖК «Victory Park»» читается хуже, чем отсутствие внешней пары.
    """
    clipped = clip(text, limit)
    if not clipped:
        return ""
    if "«" in clipped or "»" in clipped:
        return clipped
    return f"«{clipped}»"


def clip(text: str, limit: int) -> str:
    """Обрезать название карточки, не оставив висящей кавычки.

    Названия сделок сплошь содержат кавычки: «Катерина Прайм + ЖК «Victory
    Park Residences»». Обрезанное по символам, такое название теряет
    закрывающую кавычку, и строка отчёта выглядит сломанной ровно там, где
    от неё ждут точности.

    Режется по границе слова, если та не слишком далеко от предела: обрывок
    посреди слова читается хуже, чем название на два слова короче.
    """
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    cut = text[:limit].rstrip()
    space = cut.rfind(" ")
    if space > limit * 0.6:
        cut = cut[:space]
    cut = cut.rstrip(" ,;:—-")
    # Незакрытая кавычка закрывается, а не отбрасывается вместе с куском
    # названия: «ЖК «Victory Park…» читается, «ЖК…» — уже нет.
    if cut.count("«") > cut.count("»"):
        cut += "…»"
        return cut
    return cut + "…"
