def work_window_days(profile: FunnelProfile, stage_id: str) -> int:
    """Сколько дней у брокера есть на след работы по этому этапу."""
    table = profile.work_window_days
    if stage_id in table:
        return int(table[stage_id])
    return int(table.get("_default", 7))


def judgement_starts_after(profile: FunnelProfile, stage_id: str) -> float:
    """С какого возраста карточки вообще можно судить о работе, в часах.

    Двум часам на одной карточке расходиться нельзя. На «Подборе» отсрочка
    полноты — 72 часа, окно работы — 2 дня, и карточка возрастом 53 часа
    получала обе строки разом: «рано судить» и «работа не подтверждена».
    Отсрочка — это решение агентства о том, когда с брокера вообще начинают
    спрашивать, и она старше окна: берём наибольшее из двух.
    """
    grace = profile.grace_hours
    hours = int(grace.get(stage_id, grace.get("_default", 24)))
    return max(float(hours), work_window_days(profile, stage_id) * 24.0)


def _is_open_task(event: dict[str, Any]) -> bool:
    """Незакрытое дело — то есть план, а не запись о сделанном."""
    return (
        event.get("kind") == "activity"
        and str(event.get("completed") or "").upper() != "Y"
    )


def evidence_of_the_broker(
    events: list[dict[str, Any]],
    authors: set[int] | None,
) -> list[dict[str, Any]]:
    """События без чужих следов: считаем брокера и его РОПа.

    Решение агентства от 28.08, в два приёма. Сначала про дела: дело,
    заведённое бизнес-процессом или роботом, может нести длинный типовой
    текст — и по всем правилам ниже оно засчитывалось брокеру как его
    работа, его пауза и его контроль над карточкой. Потом про комментарии:
    их правило то же, и оно совпало с правилом основного аудита, который
    авторов фильтровал с самого начала (`_allowed_comment_authors`).

    Что остаётся всегда:

    * закрытые активности — запись о состоявшемся разговоре. Решение
      агентства от 28.08: «если был звонок, считать за активность брокера,
      это считается касанием». Кто отметил звонок в CRM — робот, бэк-офис
      или сам брокер, — для факта разговора неважно, и «последний след
      брокера» такой звонок обновляет по праву;
    * расшифровки — это сам разговор.

    Автор неизвестен или список авторов пуст — событие засчитываем. Мы не
    знаем, чьё оно, и превращать своё незнание в претензию к брокеру нельзя:
    это то же самое отсутствие данных, выданное за результат.
    """
    if not authors:
        return events
    kept: list[dict[str, Any]] = []
    for event in events:
        if not (_is_open_task(event) or event.get("kind") == "comment"):
            kept.append(event)
            continue
        author = event.get("author_id")
        if not isinstance(author, int) or author <= 0 or author in authors:
            kept.append(event)
    return kept


def _parse(value: Any) -> datetime | None:
    text = str(value or "").strip()
    if not text:
        return None
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def events_in_window(
    events: list[dict[str, Any]],
    now: datetime,
    days: int,
) -> list[dict[str, Any]]:
    """События за последние ``days`` дней.

    Событие с неразбираемой датой считается свежим: пропустить работу брокера
    хуже, чем лишний раз её засчитать.
    """
    edge = now - timedelta(days=days)
    fresh: list[dict[str, Any]] = []
    for event in events:
        created = _parse(event.get("created"))
        if created is None or created >= edge:
            fresh.append(event)
    return fresh


def _has_call(events: list[dict[str, Any]]) -> bool:
    """Состоявшийся звонок либо расшифровка разговора."""
    for event in events:
        if event.get("kind") == "transcript":
            return True
        if event.get("kind") != "activity":
            continue
        if int(event.get("type_id") or 0) != CALL_ACTIVITY_TYPE_ID:
            continue
        # Незакрытое дело «позвонить» — это план, а не звонок.
        if str(event.get("completed") or "").upper() == "Y":
            return True
    return False


def _has_call_attempt(events: list[dict[str, Any]]) -> bool:
    """Хотя бы попытка дозвона, снятая трубка или нет.

    Отдельно от _has_call: «клиент не отвечает» — самое удобное объяснение
    бездействия, и проверять его надо не по факту разговора, а по факту
    попытки. Несостоявшийся звонок тоже оставляет активность в таймлайне.
    """
    for event in events:
        if event.get("kind") == "transcript":
            return True
        if event.get("kind") != "activity":
            continue
        if int(event.get("type_id") or 0) == CALL_ACTIVITY_TYPE_ID:
            return True
    return False


# Сколько осмысленного текста должно быть в деле, чтобы засчитать его работой.
# Порог тот же, что агентство уже приняло для «развёрнутого комментария»:
# BUYER_OFER_MIN_COMMENT_LEN = 30 символов (src/tools.py). Одна планка на
# запись брокера, где бы он её ни оставил — в комментарии или в деле.
#
# Сначала планка стояла вдвое выше: считалось, что план отвечает на два
# вопроса (что брокер сделает и почему), а комментарий на один. Решение
# агентства от 31.08 эту разницу сняло: текст в деле засчитывается работой
# брокера, и делить его на «план» и «отчёт» не надо. #16602 — брокер
# позвонил, номер оказался чужим, и записал это в название дела: «неверный
# телефон котегарически отрицает». Тридцать девять символов, по старой
# планке не проходило, и отчёт советовал ему «выполнить» дело, которое он
# уже выполнил.
TASK_PLAN_MIN_LEN = 30

# Плейсхолдеры маскировки. «Звонок ТЕЛЕФОН_1 КЛИЕНТ_1 ПОЧТА_1» — 33 символа
# чистой пустоты, которые иначе перепрыгнули бы порог. Считаем по тому, что
# брокер действительно написал.
_MASK_PLACEHOLDER_RE = re.compile(r"(?:КЛИЕНТ|ТЕЛЕФОН|ПОЧТА)_\d+")

# Шаблонные темы Битрикса. Дело, в котором нет ничего, кроме них, — это не
# план, а его отсутствие: «Позвонить» не говорит ни что брокер сделает, ни
# почему. Список закрывает самые частые темы; порог длины закрывает остальное.
#
# Сравниваем по началу слова, а не целиком: русский шаблон приходит в любом
# падеже — «звонок клиенту», «звонка клиенту», «созвон с клиентом». Список
# точных форм пришлось бы держать в четырёх падежах, и первая же забытая
# форма пропускала бы заглушку как план.
_TASK_TEMPLATE_STEMS = (
    "позвон", "перезвон", "созвон", "звон", "набра", "набер",
    "связ", "напис", "напомн", "уточн", "провер", "выясн",
    "встреч", "показ", "задач", "дел", "клиент", "контрол", "обзвон",
    "работ", "срочн", "важн", "надо", "нужно",
)
# Предлоги и союзы: они не шаблон, но и содержания не несут. Без них строка
# «Позвонить по клиенту и по клиенту» распадалась бы на «непустые» слова.
_TASK_STOP_WORDS = frozenset({
    "в", "во", "с", "со", "по", "и", "на", "к", "у", "о", "об", "за", "до",
    "для", "от", "не", "же", "а", "но", "или",
})

_WORD_RE = re.compile(r"[^\W\d_]+", re.UNICODE)


def _is_template_word(word: str) -> bool:
    """Слово из шаблонной темы Битрикса, а не из плана брокера."""
    return word in _TASK_STOP_WORDS or word.startswith(_TASK_TEMPLATE_STEMS)


def _task_plan_text(event: dict[str, Any]) -> str:
    """Что брокер написал в деле, без нашей отсебятины и без масок.

    Читаем subject и description, а не готовое поле text: в text аудитор
    подставляет собственные строки («Дело без описания», «Исходящий звонок
    (без описания)») тем делам, где брокер не написал ничего. Засчитать
    такую подстановку за план брокера значит выдать отсутствие данных за
    результат — ровно то, чего в этом отчёте делать нельзя.
    """
    parts = [
        str(event.get("subject") or "").strip(),
        str(event.get("description") or "").strip(),
    ]
    body = " ".join(part for part in parts if part)
    body = _MASK_PLACEHOLDER_RE.sub(" ", body)
    return " ".join(body.split())


def _task_has_the_brokers_words(event: dict[str, Any]) -> bool:
    """В деле есть запись брокера, а не одна шаблонная тема.

    Один предикат на два вопроса: засчитать ли дело работой и закрывает ли
    оно собственный срок. Плана от отчёта не отличаем — решение агентства
    от 31.08.
    """
    body = _task_plan_text(event)
    if len(body) < TASK_PLAN_MIN_LEN:
        return False
    words = [w.lower() for w in _WORD_RE.findall(body)]
    return bool(words) and not all(_is_template_word(word) for word in words)


def _task_plan_state(
    events: list[dict[str, Any]],
    now: datetime,
    window_days: int,
) -> tuple[str, str]:
    """Что говорят дела карточки: PROVEN_BY_TASK_PLAN / GAP_PLAN_TOO_FAR /
    GAP_ONLY_PLANS.

    Решение агентства от 28.08, уточнённое 31.08. Признак считает код:
    засчитывается текст брокера длиной от TASK_PLAN_MIN_LEN, в котором есть
    что-то помимо шаблонной темы. Спросить об этом модель было бы проще и
    хуже: суждение о работе человека должно быть оспоримым по буквам, а не
    по впечатлению.

    Плана от отчёта мы НЕ отличаем — решение агентства от 31.08. «Позвонить
    клиенту и обсудить условия» и «неверный телефон, отрицает продажу» — оба
    записи брокера о работе, и делить их значило бы строить догадку о
    наклонении глагола там, где важен сам факт записи.

    Дело должно быть живым — незакрытым и с разбираемым сроком. Дело без
    срока (Битрикс ставит 9999-12-31) не держит ничего: засчитав его, мы
    вернули бы «Дело стоит на 9999-12-31 — ждём».

    Срок В БУДУЩЕМ должен укладываться в норму этапа. Без этого правило
    вырождается ровно так же, как выродилась бы пауза без
    _pause_covers_the_task: достаточно один раз подробно расписать дело на
    два года вперёд — и работа за каждое окно засчитана навсегда. Норма
    этапа — это и есть срок, за который агентство ждёт возврата к клиенту.
    Наступивший срок горизонта не требует: он уже прошёл, и запись под ним
    говорит о сделанном, а не откладывает.
    """
    horizon = now + timedelta(days=window_days)
    described_but_far = False
    # Что написано в самом коротком деле. Порог TASK_PLAN_MIN_LEN решает
    # судьбу карточки, и без текста РОП его проверить не может: «в деле не
    # сказано, что и почему» звучит одинаково и про «Позвонить», и про
    # четыре строки разбора. Показываем, что там на самом деле.
    shortest = ""
    for event in events:
        if event.get("kind") != "activity":
            continue
        if str(event.get("completed") or "").upper() == "Y":
            continue
        deadline = _parse(event.get("deadline"))
        if deadline is None or deadline.year >= NO_DEADLINE_YEAR:
            continue
        body = _task_plan_text(event)
        if not _task_has_the_brokers_words(event):
            if body and (not shortest or len(body) < len(shortest)):
                shortest = body
            continue
        if deadline > horizon:
            # План есть, вопрос к сроку. Претензию называем по-настоящему.
            described_but_far = True
            continue
        return PROVEN_BY_TASK_PLAN, body
    if described_but_far:
        return GAP_PLAN_TOO_FAR, ""
    return GAP_ONLY_PLANS, shortest


def _day_start(moment: datetime) -> datetime:
    """Начало суток по времени портала."""
    return moment.astimezone(PORTAL_TZ).replace(
        hour=0, minute=0, second=0, microsecond=0,
    )


def due_task_without_result(
    events: list[dict[str, Any]],
    now: datetime | None = None,
) -> dict[str, Any] | None:
    """Дело, срок которого настал, а результата в карточке нет.

    Правило агентства: если дело запланировано на сегодня, то сегодня должен
    быть комментарий о результате связи с клиентом. Само дело результатом не
    считается — это план; за результат идут комментарий, расшифровка или
    закрытое дело (звонок состоялся и его отметили).

    Час срока решает не «спрашивать или нет», а КАК об этом сказать. Раньше
    дело со сроком в 18:00, прочитанное в 10 утра, не попадало сюда вовсе:
    обвинять брокера до наступления срока нельзя. Но решение агентства от
    28.08 — «если дело запланировано на тот же день когда идёт аудит, то
    тоже надо просто напомнить что необходимо его выполнить», — а
    напоминание обвинением не является. Поэтому в рассмотрение попадает
    весь сегодняшний день портала, а разделяет случаи флаг due_today.

    Результат ищется с начала суток срока, а не с самой минуты: брокер,
    позвонивший в 11 и поставивший дело на 12, работу сделал.

    Возвращает {deadline, subject, days_overdue, due_today} или None.
    """
    now = now or datetime.now(timezone.utc)
    today = _day_start(now)
    candidates: list[tuple[datetime, str, dict[str, Any]]] = []
    for event in events:
        if event.get("kind") != "activity":
            continue
        if str(event.get("completed") or "").upper() == "Y":
            continue
        deadline = _parse(event.get("deadline"))
        if deadline is None:
            continue
        # Дело без срока Битрикс метит 9999-12-31. Это не «дело на будущее»
        # и тем более не наступивший срок — пропускаем.
        if deadline.year >= NO_DEADLINE_YEAR:
            continue
        if _day_start(deadline) > today:
            continue
        candidates.append(
            (deadline, str(event.get("subject") or "").strip(), event),
        )
    if not candidates:
        return None

    results = [
        created for created in (
            _parse(event.get("created")) for event in events
            # Незакрытое дело — это план, а не отчёт о результате.
            if event.get("kind") != "activity"
            or str(event.get("completed") or "").upper() == "Y"
        )
        if created is not None
    ]

    # Отписку ищем по КАЖДОМУ делу отдельно, а не по самому старому. Пока
    # проверка шла от начала суток первого дела, одно забытое дело трёхмесячной
    # давности гасило напоминание по всем остальным: любой комментарий за эти
    # три месяца засчитывался за результат по делу, поставленному сегодня.
    # Долг считается от первого дела, по которому отписки НЕТ.
    for due, subject, _event in sorted(candidates, key=lambda c: c[0]):
        # Текст дела срок НЕ закрывает, хотя работой он засчитывается.
        # Час назад закрывал — и напоминания посыпались: «Связаться с
        # клиентом-обратная связь» это обычное имя дела, тридцать пять
        # символов, и оно гасило собственный срок. #16230 потеряла
        # напоминание о деле на сегодня, а решение агентства от 28.08
        # говорит его давать.
        #
        # Отличить отчёт («неверный телефон отрицает») от имени дела
        # («связаться — обратная связь») можно только разбором наклонения
        # глагола, а от него агентство отказалось 31.08. Значит развилки
        # нет, и выбирать надо между «нет напоминаний почти нигде» и «есть
        # напоминание, которое не требует переделать сделанное». Второе
        # решается формулировкой совета — см. next_action.
        since = _day_start(due)
        if any(created >= since for created in results):
            continue
        overdue = int((today - since).total_seconds() // 86400)
        return {
            "deadline": since.date().isoformat(),
            "subject": subject,
            "days_overdue": max(0, overdue),
            # Час срока ещё не настал: «срок прошёл» было бы неправдой.
            "due_today": due > now,
        }
    return None


def _pause_is_running(pause_explained: bool, pause_until: str,
                      now: datetime) -> bool:
    """Названная пауза ещё не кончилась по календарю.

    Отвечаем «да» только тогда, когда это видно из карточки: причина названа
    И назван срок И срок в будущем. Пауза без срока («клиент подумает»,
    «вернётся из отпуска») сюда не попадает намеренно — по ней нельзя
    показать, что ожидание продолжается, а значит нельзя и снять с карточки
    вопрос о заброшенности. Это та самая дыра, ради которой заброшенность
    вообще подняли наверх: объяснение, к которому брокер не вернулся
    полгода, перестаёт быть объяснением.
    """
    if not pause_explained:
        return False
    ends = _parse(pause_until)
    if ends is None:
        return False
    return ends > now


def _pause_covers_the_task(
    pause_until: str,
    deadline: datetime,
    now: datetime,
    window_days: int,
) -> bool:
    """Названная причина объясняет именно этот срок, а не любой.

    Без этой проверки правило вырождается: достаточно поставить дело на три
    месяца вперёд, приписать «клиент в отпуске» — и брокер чист навсегда.
    Поэтому срок дела должен укладываться в названную паузу плюс норму этапа
    на то, чтобы после неё выйти на связь.

    Срок паузы не назван («до сентября», «когда вернётся») — проверять нечем;
    тогда правило держится на остальном: причина названа дословно в карточке,
    и дело по карточке стоит.
    """
    ends = _parse(pause_until)
    if ends is None:
        return True
    if ends <= now:
        # Пауза кончилась — ожидание больше не оправдание.
        return False
    return deadline <= ends + timedelta(days=window_days)


def _ball_is_theirs(who: str, when: str, now: datetime) -> bool:
    """Ход за контрагентом, и названный им срок ещё не прошёл.

    Неразбираемый срок («в начале сентября») считается ненаступившим: не
    сумели прочитать дату — это наша слепота, а не просрочка брокера. Как
    только срок прошёл по календарю, ожидание кончилось и карточка снова
    судится обычными правилами.
    """
    if str(who or "").strip().lower() != "client":
        return False
    return _date_state(str(when or ""), now) != "past"


def has_a_conversation(events: list[dict[str, Any]]) -> bool:
    """Состоялся ли разговор: снятая трубка или расшифровка.

    Публичная обёртка над той же проверкой, по которой карточка получает
    PROVEN_BY_CALL. Нужна шапке отчёта: строка «звонки есть у N карточек»
    отвечает на тот же вопрос, что и строка внутри карточки, и отвечать
    иначе не может.

    Прогон 31.08: шапка говорила «звонки есть у 1 из 10», а #10994 —
    «ни звонка, ни комментария брокера 106 дн.». Пропущенный входящий
    звонок разговором не был, но в счётчик шапки попадал: он считался по
    has_any_call, где непринятый вызов тоже звонок. Два ответа на один
    вопрос в одном отчёте.
    """
    return _has_call(events)


def has_any_call(events: list[dict[str, Any]]) -> bool:
    """Была ли ПОПЫТКА связи — снятая трубка или нет.

    Не то же самое, что has_a_conversation, и путать их нельзя. Здесь
    вопрос другой: есть ли в таймлайне след контакта. Непринятый вызов —
    ровно такой след, и для утверждения «клиент не отвечает» он и есть
    доказательство. Единственный потребитель — проверка молчания
    контрагента: без следа мы это молчание не утверждаем.

    Направление агентство решило не различать: входящий звонок — тоже
    контакт, и ставить брокеру в упрёк, что позвонил клиент, а не он,
    значит требовать инициативы там, где важен сам факт связи.
    """
    for event in events:
        if event.get("kind") == "transcript":
            return True
        if event.get("kind") != "activity":
            continue
        if int(event.get("type_id") or 0) == CALL_ACTIVITY_TYPE_ID:
            return True
    return False


def comment_without_a_call(
    events: list[dict[str, Any]],
    *,
    profile: FunnelProfile,
    stage_id: str,
    comment_informative: bool,
    hours_on_stage: float | None = None,
    now: datetime | None = None,
) -> bool:
    """Работа описана комментарием, а звонка в таймлайне нет.

    Не обвинение, а пометка: комментарий брокера — это его же слова о своей
    работе, и подтвердить их нечем. Сверять пересказ с расшифровкой мы
    перестали, поэтому смотрим на то, что видно всегда: был ли по карточке
    разговор — исходящий или входящий, всё равно.
    """
    now = now or datetime.now(timezone.utc)
    if hours_on_stage is not None and hours_on_stage < judgement_starts_after(
        profile, stage_id,
    ):
        # #16976 стояла в «рано судить» — и тут же получала пометку. Отсрочка
        # этапа — это решение о том, когда с брокера вообще начинают
        # спрашивать; молчать она должна для всех строк отчёта, а не только
        # для оценки работы.
        return False
    window = events_in_window(events, now, work_window_days(profile, stage_id))
    if not comment_informative:
        # Про пустой комментарий уже сказано отдельной строкой.
        return False
    if not any(e.get("kind") == "comment" for e in window):
        return False
    return not has_any_call(window)


def assess_broker_work(
    events: list[dict[str, Any]],
    *,
    profile: FunnelProfile,
    stage_id: str,
    hours_on_stage: float | None,
    claims_messaged: bool,
    comment_informative: bool,
    claims_no_answer: bool = False,
    abandoned_days: float = 0.0,
    next_step_who: str = "",
    next_step_when: str = "",
    pause_explained: bool = False,
    pause_until: str = "",
    task_authors: set[int] | None = None,
    now: datetime | None = None,
) -> dict[str, Any]:
    """Подтверждена ли работа брокера за последнее окно по этапу.

    Возвращает {proven, reason, window_days, days_quiet}. days_quiet — дней с
    последнего любого следа в карточке; None, если следов нет вовсе.
    """
    now = now or datetime.now(timezone.utc)
    days = work_window_days(profile, stage_id)
    # Чужие следы в зачёт не идут — решение агентства от 28.08: считаются
    # дела и комментарии брокера и его РОПа. Отсекаем один раз здесь: дальше
    # по цепочке одно и то же событие засчитывается работой, паузой,
    # ожиданием, отпиской по делу и признаком «карточку держат», и во всех
    # этих местах ответ должен быть один и тот же.
    events = evidence_of_the_broker(events, task_authors)
    window = events_in_window(events, now, days)

    last_seen: datetime | None = None
    for event in events:
        created = _parse(event.get("created"))
        if created is not None and (last_seen is None or created > last_seen):
            last_seen = created
    # Округляем: «12.070261341574074 дня» — не точность, а шум. Он уходил в
    # state_json, менялся каждую секунду и случайно совпадал с цифрами
    # телефона, из-за чего тест маскировки падал примерно раз на сотню
    # прогонов. Отчёту хватает одного знака.
    days_quiet = (
        round((now - last_seen).total_seconds() / 86400.0, 1)
        if last_seen else None
    )

    # Брошенная карточка проверяется первой — раньше паузы, хода за
    # контрагентом и срока дела. Так было не всегда: заброшенность стояла
    # последней, «объяснённое молчание — не забвение». Но пауза и ожидание
    # часов не имеют, и карточка с записанной когда-то паузой оставалась
    # напоминанием при двухстах днях тишины — то есть не поднималась вообще
    # ничем. Решение агентства от 28.08 называет «брошен на этапе долгое
    # время» потерей клиента, а потеря старше любого напоминания: объяснение,
    # к которому брокер не вернулся полгода, перестаёт быть объяснением.
    #
    # Но только пока на контроле ничего не стоит. Брошена — это когда
    # карточку никто не держит; незакрытое дело со сроком в будущем значит,
    # что держит, даже если разговор отложен на месяцы («клиент вернётся из
    # отпуска в ноябре», дело на ноябрь). Иначе брокер, записавший причину и
    # поставивший дело, получал бы «карточка брошена» — то есть назвать
    # причину было бы хуже, чем промолчать, а такие правила уже приходилось
    # переворачивать обратно. Срок дела при этом проверяют ветки ниже:
    # пауза — через _pause_covers_the_task, план — через норму этапа.
    silent = days_quiet
    if silent is None and hours_on_stage is not None:
        # Событий нет вовсе — считаем от возраста карточки на этапе.
        silent = hours_on_stage / 24.0
    on_control = has_open_future_task(events, now)
    # ...и пока не идёт названная пауза. #11690: «клиент отложила решение до
    # октября», записано тридцать один день назад, дела нет — и карточка
    # получала «брошена 31 дн.» вместо напоминания поставить дело. Любая
    # пауза длиннее месяца выходила за порог заброшенности, то есть решение
    # агентства от 28.08 («паузу записал, дела нет вовсе — напомнить»)
    # молча переставало работать для всех длинных пауз. Пауза с названным
    # сроком в будущем — это ответ на вопрос «почему тихо», и пока срок не
    # прошёл, спор идёт о деле, а не о брошенной карточке. Пауза без срока
    # заброшенность по-прежнему не отменяет: по ней не видно, что ожидание
    # продолжается.
    pause_running = _pause_is_running(pause_explained, pause_until, now)
    abandoned = bool(
        abandoned_days > 0
        and silent is not None
        and silent >= abandoned_days
        and not on_control
        and not pause_running
    )

    def _finish(reason: str, **extra: Any) -> dict[str, Any]:
        """Собрать ответ и добавить к нему просроченное дело, если оно есть.

        Просрочка доезжает до любого исхода, а не только до последнего:
        ветки паузы, ожидания и отсрочки возвращают результат раньше, и
        раньше теряли её молча.
        """
        out: dict[str, Any] = {
            "proven": reason in PROVEN,
            "reason": reason,
            "window_days": days,
            "days_quiet": days_quiet,
        }
        out.update(extra)
        if due is None:
            return out
        # Дело просрочено. Претензию оно не отменяет — решение агентства от
        # 28.08: «претензия может быть только если дело просрочено». Если по
        # карточке и так не видно работы, разговор о ней, а не о том, что
        # дело пора закрыть. Но саму просрочку РОП должен видеть в любом
        # случае: кладём её доводом.
        out["due_task"] = due
        # Спрашиваем не про членство в PROVEN, а про сам флаг: отсрочка этапа
        # возвращает proven=True с кодом GAP_OUT_OF_WINDOW, которого в PROVEN
        # нет. Проверка по множеству молча пропускала бы именно тот случай,
        # ради которого всё это писалось, — молодую карточку с делом, срок
        # которого брокер назначил себе сам.
        claimed = (
            not out["proven"]
            and reason not in REMINDERS
            and reason not in YIELDS_TO_OVERDUE
        )
        if not claimed:
            # Претензии нет — остаётся напоминание, и оно конкретнее любого
            # другого: у него есть дело и дата.
            out["proven"] = False
            out["reason"] = GAP_DUE_TASK_NO_RESULT
        return out

    # Дело со сроком. Решение агентства от 28.08 разделило два случая, и
    # разделило по существу: «претензия может быть только если дело
    # просрочено».
    #
    # Дело стоит на СЕГОДНЯ — день не кончился, спрашивать не с чего:
    # напоминаем и на этом останавливаемся. Проверка стоит раньше окна
    # этапа и раньше звонка (обязательство брокер назначил себе сам, и
    # молодость карточки его не отменяет) и ниже заброшенности —
    # напоминать о деле на карточке, брошенной сто дней назад, значит
    # говорить не о том.
    due = due_task_without_result(events, now)
    # Заброшенность — первой. Когда я вводил общий выход _finish, эта
    # проверка съехала ниже дела на сегодня, и карточка, молчащая двести
    # дней, получала «дело стоит на сегодня — выполнить» вместо «брошена
    # 200 дн.». Дело со сроком сегодня утром живым не считается
    # (open_future_deadline требует срок в будущем), поэтому от
    # заброшенности оно карточку не спасает — и не должно: по определению
    # агентства «брошен на этапе долгое время» это потеря, а потеря старше
    # любого напоминания.
    if abandoned:
        return _finish(
            GAP_ABANDONED, abandoned_days=round(float(silent or 0.0), 1),
        )
    if due is not None and int(due.get("days_overdue") or 0) < 1:
        return {
            "proven": False,
            "reason": GAP_TASK_DUE_TODAY,
            "window_days": days,
            "days_quiet": days_quiet,
            "due_task": due,
        }

    # Просроченное дело претензию НЕ гасит: оно разбирается в самом конце,
    # после того как цепочка сказала своё. Иначе самый мягкий вердикт
    # перебивал самый тяжёлый — карточка без единого следа работы получала
    # «напоминание: срок дела прошёл» вместо «следов работы нет вовсе».

    # Карточка младше отсрочки этапа: спрашивать не с чего.
    if hours_on_stage is not None and hours_on_stage < judgement_starts_after(
        profile, stage_id,
    ):
        return _finish(GAP_OUT_OF_WINDOW, proven=True)

    # Пауза с названной причиной: клиент в отпуске, ждёт документы, продаёт
    # свою квартиру. Ход при этом может числиться за брокером — выйти на связь
    # после паузы всё равно ему, — но спрашивать с него за тишину, причину
    # которой он же и записал в карточку, значит наказывать за аккуратность.
    # Ждать можно только с делом: без него это не пауза, а забытьё.
    if pause_explained:
        deadline = open_future_deadline(events, now)
        if deadline is None:
            return _finish(GAP_PAUSE_NO_TASK)
        if _pause_covers_the_task(pause_until, deadline, now, days):
            return _finish(
                PROVEN_BY_PAUSE, pause_until=pause_until or "unknown",
            )
        return _finish(
            GAP_PAUSE_TASK_TOO_LATE,
            pause_until=pause_until or "unknown",
            task_deadline=deadline.astimezone(PORTAL_TZ).date().isoformat(),
        )

    # Ход за контрагентом: он сам назвал, когда вернётся к разговору. Молчание
    # брокера тут не бездействие. #16798: агент сказал, что наберёт в начале
    # сентября и приедет с покупателем, — а карточка ушла в «недоработку» за
    # пять дней тишины. Ждать можно, но только с делом на контроле: без него
    # ожидание ничем не отличается от забытья, и это не обвинение, а повод
    # напомнить.
    if _ball_is_theirs(next_step_who, next_step_when, now):
        return _finish(
            PROVEN_BY_WAITING if on_control else GAP_WAITING_NO_TASK,
        )

    # Ветка «комментарий» смотрит на комментарии и на текст дела. Пустое
    # дело — «Позвонить» — работой по-прежнему не считается: план, который
    # нельзя проверить, ничем не отличается от его отсутствия. Но дело, где
    # написано, что брокер сделает и почему, засчитывается — решение
    # агентства от 28.08. Считаем по окну этапа: дело, написанное сорок дней
    # назад, в окно не попадёт и бессрочной индульгенцией не станет.
    comments = [e for e in window if e.get("kind") == "comment"]
    plan_text = ""
    if _has_call(window):
        reason = PROVEN_BY_CALL
    elif not comments:
        # Три разных упрёка, которые раньше звучали одинаково: пусто вовсе,
        # одни планы, и работа была — но раньше нормы этапа.
        if window:
            reason, plan_text = _task_plan_state(window, now, days)
        elif last_seen is None:
            reason = GAP_NO_TRACE
        else:
            reason = GAP_NO_TRACE_IN_WINDOW
    elif claims_no_answer and not _has_call_attempt(window):
        # «Не дозвонился» проверяется первым: это объяснение бездействия, и
        # оно должно стоить дороже остальных. Есть попытки — брокер работал,
        # даже если трубку не взяли; нет попыток — работы не было.
        reason = GAP_CLAIMED_NO_ANSWER
    elif claims_messaged:
        # Утверждение «написал клиенту» засчитывается только со скриншотом.
        has_screenshot = any(e.get("has_files") for e in comments)
        reason = PROVEN_BY_SCREENSHOT if has_screenshot else GAP_CLAIMED_MESSAGE
    elif not comment_informative:
        reason = GAP_EMPTY_COMMENT
    else:
        reason = PROVEN_BY_COMMENT

    if reason == GAP_ONLY_PLANS and plan_text:
        return _finish(reason, task_text=plan_text)
    return _finish(reason)


def open_future_deadline(
    events: list[dict[str, Any]],
    now: datetime | None = None,
) -> datetime | None:
    """Ближайший срок незакрытого дела в будущем, или None."""
    now = now or datetime.now(timezone.utc)
    nearest: datetime | None = None
    for event in events:
        if event.get("kind") != "activity":
            continue
        if str(event.get("completed") or "").upper() == "Y":
            continue
        deadline = _parse(event.get("deadline"))
        if deadline is None or deadline <= now:
            continue
        if deadline.year >= NO_DEADLINE_YEAR:
            # Дело без срока. Оно есть, но ничего не держит.
            continue
        if nearest is None or deadline < nearest:
            nearest = deadline
    return nearest


def has_open_future_task(
    events: list[dict[str, Any]],
    now: datetime | None = None,
) -> bool:
    """Есть ли по карточке незакрытое дело со сроком в будущем."""
    return open_future_deadline(events, now) is not None


_DATE_IN_TEXT = re.compile(r"\d{4}-\d{2}-\d{2}|\d{1,2}\.\d{1,2}\.\d{4}")


def _extract_date(text: str) -> datetime | None:
    """Дата из срока, даже если она внутри фразы.

    #11952: срок записан как «сегодня - завтра (2026-08-03 - 2026-08-04)».
    Строка целиком не разбирается, и совет выходил «уточнить дату» — про
    даты, которые прошли три недели назад и написаны прямо в ней же.
    Из диапазона берём последнюю дату: срок кончается ею, а не началом.
    """
    whole = _parse(text)
    if whole is not None:
        return whole
    found: list[datetime] = []
    for chunk in _DATE_IN_TEXT.findall(str(text or "")):
        if "." in chunk:
            day, month, year = chunk.split(".")
            chunk = f"{year}-{int(month):02d}-{int(day):02d}"
        parsed = _parse(chunk)
        if parsed is not None:
            found.append(parsed)
    return max(found) if found else None


def _date_state(text: str, now: datetime) -> str:
    """Срок: "future" / "past" / "" (не дата).

    Прошедшая дата — не то же самое, что будущая. Совет «запланировать дело
    на 19 августа», когда сегодня 26-е, читается как издёвка: срок уже
    сорван, и планировать надо не его, а разговор о новом.
    """
    parsed = _extract_date(text)
    if parsed is None:
        return ""
    return "future" if parsed > now else "past"


def next_action(
    state: dict[str, Any],
    events: list[dict[str, Any]],
    now: datetime | None = None,
    task_authors: set[int] | None = None,
) -> str:
    """Что брокеру сделать по карточке прямо сейчас, или "" если нечего.

    Отчёт, который сообщает «не хватает следующего шага с датой», ставит
    диагноз. РОПу нужен рецепт: дело в Битриксе, с датой. Особенно когда
    ход за клиентом — «собственник вывезет мусор, потом фотосессия» — такая
    карточка выглядит брошенной, хотя брокер просто ждёт. Ждать можно, но
    с запланированным делом, иначе ожидание ничем не отличается от забытья.
    """
    now = now or datetime.now(timezone.utc)
    # Тот же отбор, что и в оценке работы: иначе совет назовёт срок чужого
    # дела, которого оценка не видела, и две строки одной карточки разойдутся.
    events = evidence_of_the_broker(events, task_authors)

    work = state.get("work_evidence") if isinstance(
        state.get("work_evidence"), dict
    ) else {}
    if str(work.get("reason") or "") == GAP_ABANDONED:
        # По забытой карточке не «закройте дело» — тут решают, ведём мы её
        # дальше или нет, и это решение РОПа, а не напоминание брокеру.
        # Проверяется раньше срока дела: тот же порядок, что в оценке работы,
        # иначе строка карточки скажет «брошена», а совет — «выполните дело».
        quiet = work.get("abandoned_days")
        span = f"{float(quiet):.0f} дн." if isinstance(quiet, (int, float)) else "месяцы"
        return (
            f"Карточка брошена {span} — решить: возвращать клиента в работу "
            f"или закрывать сделку"
        )

    due = due_task_without_result(events, now)
    if due is not None:
        subject = str(due.get("subject") or "").strip()
        tail = f" по делу «{subject}»" if subject else ""
        # «Если уже сделано — закрыть дело» стоит в обоих советах не для
        # красоты. #16602: брокер позвонил, номер оказался чужим, и записал
        # это в НАЗВАНИЕ дела — «неверный телефон котегарически отрицает».
        # Дело осталось открытым, комментария нет, и совет требовал
        # «выполнить», то есть сделать сделанное. Отличить отчёт в названии
        # от обычного имени дела код не может — от разбора наклонения
        # глагола агентство отказалось 31.08, — но и не должен: обе
        # половины совета верны, брокер сам знает, которая про него.
        if int(due.get("days_overdue") or 0) >= 1:
            return (
                f"Срок дела {due['deadline']} прошёл, результата в карточке нет — "
                f"связаться с клиентом и написать результат{tail}; "
                f"если уже сделано, закрыть дело"
            )
        # Весь день срока — один случай, и час внутри него ничего не меняет:
        # решение агентства «претензия может быть только если дело
        # просрочено». Отдельная формулировка для «час уже прошёл» ставила
        # под строкой «дело стоит на сегодня» совет «срок уже прошёл» — два
        # регистра об одном и том же на одной карточке.
        return (
            f"Дело стоит на сегодня ({due['deadline']}) — "
            f"выполнить и написать в карточке результат{tail}; "
            f"если уже сделано, закрыть дело"
        )

    if str(work.get("reason") or "") == GAP_PLAN_TOO_FAR:
        scheduled = open_future_deadline(events, now)
        window = work.get("window_days")
        span = (
            f"норма этапа — {window} дн."
            if isinstance(window, (int, float)) else "норма этапа короче"
        )
        stands = (
            scheduled.astimezone(PORTAL_TZ).date().isoformat()
            if scheduled is not None else ""
        )
        head = f"Дело стоит на {stands}" if stands else "Дело стоит далеко"
        return (
            f"{head}, а {span} — перенести ближе или записать в карточке, "
            f"почему к клиенту возвращаемся позже"
        )

    if str(work.get("reason") or "") == GAP_PAUSE_TASK_TOO_LATE:
        # Тут спорить не с записью, а со сроком: и пауза, и дело в карточке
        # есть. Совет должен назвать обе даты — иначе «перенесите дело»
        # звучит как придирка без арифметики.
        until = str(work.get("pause_until") or "").strip()
        stands = str(work.get("task_deadline") or "").strip()
        head = (
            f"Дело стоит на {stands}" if stands else "Дело стоит слишком поздно"
        )
        tail = (
            f", а клиент возвращается {until}"
            if until and until != "unknown" else ""
        )
        return (
            f"{head}{tail} — перенести его на ближайшие дни после паузы"
        )

    fix = RECORD_FIXES.get(str(work.get("reason") or ""))
    if fix:
        # Претензия к записи в карточке отвечается записью, а не ожиданием.
        return fix

    scheduled = open_future_deadline(events, now)
    if scheduled is not None:
        # Дело уже стоит — советовать нечего, но и молчать нельзя. Пустая
        # строка в тревожном разделе оставляла РОПа с сигналом без ответа:
        # карточка помечена «теряем клиента», а что делать — не сказано.
        # Состояние — тоже ответ: ждём до названного срока.
        day = scheduled.astimezone(PORTAL_TZ).date().isoformat()
        today = day == _day_start(now).date().isoformat()
        if work and not work.get("proven"):
            # #16032: «работа не подтверждена» и «ждём» на одной карточке.
            # Незакрытое дело — это план брокера, а не работа с клиентом:
            # ровно поэтому оно и не сняло претензию двумя строками выше.
            # Отвечать этой претензии ожиданием значит советовать не делать
            # ничего по поводу того, что мы только что назвали недоработкой.
            # Состояние называем — но вместе с пробелом, а не вместо него.
            window = work.get("window_days")
            span = (
                f"за норму этапа ({window} дн.)"
                if isinstance(window, (int, float)) else "за норму этапа"
            )
            when = f"на сегодня ({day})" if today else f"на {day}"
            return (
                f"Дело стоит {when}, но следов работы {span} нет — "
                f"записать в карточке, что сейчас с клиентом"
            )
        if today:
            # «Дело стоит на 2026-08-26 — ждём» в отчёте от 26-го числа
            # заставляет читателя сверять даты, чтобы понять, что срок сегодня.
            return f"Дело стоит на сегодня ({day}) — ждать результата"
        return f"Дело стоит на {day} — ждём"

    step = state.get("next_step") if isinstance(state.get("next_step"), dict) else {}
    what = str(step.get("what") or "").strip()
    when = str(step.get("when") or "").strip()
    who = str(step.get("who") or "").strip().lower()
    dated = bool(when) and when.lower() != "unknown"

    if not what or what.lower() == "unknown":
        if state.get("counterparty_silent"):
            # #12290: «клиент не выходит на связь (не в сети, сбрасывает
            # вызовы, не отвечает)» — и совет «согласовать с клиентом
            # следующий шаг». Согласовать не с кем, и карточка сама об этом
            # говорит двумя строками выше. Совет, который нельзя выполнить,
            # брокер не выполнит и перестанет читать остальные.
            #
            # Что брокер может в одиночку: назначить следующую попытку и
            # записать прошлые — заодно закрывается дыра, из-за которой
            # «клиент не отвечает» ничем не подтверждено.
            return (
                "Клиент не выходит на связь — поставить дело на следующую "
                "попытку и записать в карточке, сколько раз уже пробовали"
            )
        return "Запланировать дело: согласовать с клиентом следующий шаг и срок"

    when_state = _date_state(when, now) if dated else ""
    # В сообщении называем разобранную дату, а не фразу целиком: «Срок сегодня
    # - завтра (2026-08-03 - 2026-08-04) прошёл» читать нельзя.
    resolved = _extract_date(when) if dated else None
    day = (
        resolved.astimezone(PORTAL_TZ).date().isoformat()
        if resolved is not None else when
    )

    if who == "client":
        # Агента называем агентом. «Проверить, выполнил ли клиент» про
        # регионального агента, который обещал приехать с покупателем, звучит
        # мимо, а терять такой контакт дороже всего: он приводит сделку.
        party = state.get("counterparty") if isinstance(
            state.get("counterparty"), dict
        ) else {}
        agent = str(party.get("who") or "") == "agent"
        noun = "агентом" if agent else "клиентом"
        loss = " — иначе контакт потеряется" if agent else ""
        if when_state == "future":
            return (
                f"Запланировать дело на {day}: связаться и проверить, "
                f"выполнено ли — {what}"
            )
        if when_state == "past":
            return (
                f"Срок {day} прошёл, ответа нет — связаться с {noun} "
                f"и назначить новый: {what}"
            )
        if dated:
            return (
                f"Запланировать дело: срок назван как «{when}» — поставить дело "
                f"на связь с {noun} и подтвердить точную дату ({what}){loss}"
            )
        return (
            f"Запланировать дело: связаться с {noun} и согласовать срок — "
            f"{what}{loss}"
        )

    if when_state == "future":
        return f"Запланировать дело на {day}: {what}"
    if when_state == "past":
        return f"Срок {day} прошёл, дела нет — связаться и назначить новый: {what}"
    if dated:
        return f"Запланировать дело: уточнить дату («{when}») и поставить — {what}"
    return f"Запланировать дело с датой: {what}"
