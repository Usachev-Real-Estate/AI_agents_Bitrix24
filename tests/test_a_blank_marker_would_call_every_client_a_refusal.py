"""Маркеры отказа: настройка, которой дороже ошибиться, чем промолчать.

Правило 2 раздела 6.2 ТЗ стоит вторым сверху и перебивает и тишину, и
«движется». Значит ложное срабатывание не добавляет строку в список, а
УБИРАЕТ её: живой клиент, которому брокер обязан позвонить, объявляется
отказавшимся и исчезает с экрана молча.

Отсюда всё, что проверяется ниже. Пустой маркер совпадает с любым текстом
и обнулил бы портфель целиком. Опечатка в переменной окружения не имеет
права выключить правило исподтишка. А отдельное слово «отказ» в списке по
умолчанию поймало бы «клиент не отказывается» — поэтому маркеры фразами.
"""

import json

import pytest

from config import REFUSAL_MARKERS, get_settings


@pytest.fixture
def markers(monkeypatch):
    """Прочитать настройку при заданном REFUSAL_MARKERS_JSON."""
    def _read(raw: str | None):
        if raw is None:
            monkeypatch.delenv("REFUSAL_MARKERS_JSON", raising=False)
        else:
            monkeypatch.setenv("REFUSAL_MARKERS_JSON", raw)
        get_settings.cache_clear()
        return get_settings().refusal_markers

    yield _read
    get_settings.cache_clear()


def test_a_blank_marker_never_reaches_the_rule(markers):
    """Пустая строка в списке вычёркивается.

    Она совпадает с любым текстом: пустая подстрока есть в каждом
    комментарии. Один пробел, оставшийся в настройке после правки, объявил
    бы отказавшимся весь портфель.
    """
    assert markers(json.dumps(["  ", "", "передумал"])) == ("передумал",)


def test_an_empty_list_switches_the_rule_off_deliberately(markers):
    """Пустой список — это «правило 2 не нужно», и так и читается.

    Осознанное отключение отличается от поломки тем, что его ВИДНО:
    прогон обязан записать правило в degraded_rules, а не молча перестать
    находить отказы.
    """
    assert markers("[]") == ()


def test_a_typo_in_the_variable_does_not_switch_the_rule_off(markers):
    """Сломанный JSON возвращает список по умолчанию, а не пустоту.

    Разница в цене. Пустой список — это «отказов не ищем»: правило
    молчит, и клиенты, которые отказались, остаются в работе у брокера.
    Опечатка в .env не должна стоить того же, и тем более незаметно.
    """
    assert markers("не json вовсе") == REFUSAL_MARKERS

    # Разобрался — ещё не значит «список». Словарь переберётся по ключам,
    # а голая строка — по БУКВАМ, и маркером станет каждая: «п» есть почти
    # в любом комментарии, и отказавшимся окажется весь портфель.
    assert markers('{"не": "список"}') == REFUSAL_MARKERS
    assert markers('"передумал"') == REFUSAL_MARKERS
    assert markers("17") == REFUSAL_MARKERS


def test_the_agency_list_wins_over_the_default(markers):
    """Свой список замещает умолчание целиком, а не дополняет его.

    Формулировки у каждого агентства свои, и «дополнить» значило бы
    навсегда оставить в правиле мои догадки, которые никто не выбирал.
    """
    assert markers(json.dumps(["снял с продажи"])) == ("снял с продажи",)


def test_the_default_markers_are_phrases_and_not_single_words(markers):
    """В умолчании нет слов, которые ловят сами себя в отрицании.

    «отказ» встречается в «клиент не отказывается» и в служебном «отказ по
    мощностям»; «дорого» брокер пишет посреди торга, а не в конце работы;
    «отложил» — это стадия «Отложенная продажа», то есть работа
    продолжается. Каждое из них убрало бы живого клиента из списка.
    """
    for trap in ("отказ", "дорого", "отложил", "не берет трубку"):
        assert trap not in REFUSAL_MARKERS, f"«{trap}» ловит живых клиентов"


def test_the_default_covers_both_sides_of_the_business(markers):
    """Покупатель передумал и собственник снял объект — оба конца работы.

    Слой считает обе воронки, и список, написанный только под покупателя,
    молча не находил бы ни одного отказа у продавцов.
    """
    assert "передумал" in REFUSAL_MARKERS
    assert "снял с продажи" in REFUSAL_MARKERS
